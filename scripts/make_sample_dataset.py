"""Generate a tiny synthetic image dataset for local testing/demos.

Creates sample_data/{cat,dog,car}/ each with a handful of small solid-color
images (mixed .jpg/.png) plus a couple of non-image files that a real scan
should skip. Not committed to git (see .gitignore).
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

OUTPUT_ROOT = Path(__file__).resolve().parent.parent / "sample_data"
LABELS = ("cat", "dog", "car")
IMAGES_PER_LABEL = 5
IMAGE_SIZE = (32, 32)


def make_dataset(root: Path = OUTPUT_ROOT) -> None:
    root.mkdir(parents=True, exist_ok=True)

    for label_index, label in enumerate(LABELS):
        label_dir = root / label
        label_dir.mkdir(parents=True, exist_ok=True)

        for i in range(IMAGES_PER_LABEL):
            color = ((label_index * 60 + i * 10) % 256, (i * 40) % 256, (label_index * 80) % 256)
            img = Image.new("RGB", IMAGE_SIZE, color=color)
            ext = "jpg" if i % 2 == 0 else "png"
            img.save(label_dir / f"{label}_{i:02d}.{ext}")

        # Non-image files that a scan should filter out.
        (label_dir / "notes.txt").write_text(f"metadata notes for {label}, not an image\n")

    (root / "README.txt").write_text(
        "Synthetic sample dataset generated by make_sample_dataset.py\n"
    )

    print(f"sample dataset created at: {root}")


if __name__ == "__main__":
    make_dataset()
